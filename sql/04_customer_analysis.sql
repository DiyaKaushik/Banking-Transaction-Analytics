-- =====================================================================
-- 04_customer_analysis.sql
-- Banking Transaction Analytics (MySQL 8.0)
--
-- Business questions
--   1. Which customer segments (age, gender, region, products) generate the most activity?
--   2. How many customers are really active over time?
--   3. How concentrated is activity among the busiest customers?
--   4. Is the rise in overdrafts spread over many accounts or concentrated in a few?
--
-- Key design decision: bank-generated postings are NOT customer activity.
--   Interest credited, penalty interest and service fees are posted by the bank, on the last day of
--   every month, to practically every account. Counting them makes almost every account look
--   "active" every month and inflates the transaction count by about a third. Customer activity here
--   means customer-initiated postings: every category except those three.
--
-- Definitions
--   customer       one account (each client has exactly one account); attributes are the OWNER's
--   tenure_months  months from account opening to 1998-12-31, counted inclusively; it makes accounts
--                  opened at different times comparable
--   intensity      customer-initiated postings per tenure month (a DOUBLE division, so that tiers can be
--                  reproduced exactly in pandas)
--   age band       owner's age when the account was opened
--   quartile 1     the LEAST active quarter of accounts; decile 1 below is the MOST valuable tenth
--
-- Run queries one at a time in MySQL Workbench, or use:
--     python scripts/validate_sql.py --file sql/04_customer_analysis.sql --show NAME
--     python scripts/validate_sql.py --file sql/04_customer_analysis.sql        (scoreboard vs pandas)
-- "Expected" values quoted in comments were derived from numbers found independently in Python.
-- =====================================================================

USE banking_analytics;


-- @query activity_split_bank_vs_customer
-- Question: how much of the activity is generated by the bank itself?
-- Expected: bank-generated 340,523 postings (32.2%) = 183,114 interest + 155,832 fees + 1,577 penalty
--           interest; customer-initiated 715,797.
-- Technique: CASE WHEN classifier, window share of total.
SELECT
    CASE
        WHEN transaction_category IN ('Interest credited', 'Penalty interest', 'Service fees')
            THEN 'Bank-generated'
        ELSE 'Customer-initiated'
    END                                                              AS posting_origin,
    COUNT(*)                                                         AS postings,
    ROUND(100 * COUNT(*) / SUM(COUNT(*)) OVER (), 2)                 AS share_of_postings_pct,
    SUM(amount)                                                      AS total_value_czk,
    ROUND(100 * SUM(amount) / SUM(SUM(amount)) OVER (), 2)           AS share_of_value_pct,
    ROUND(AVG(amount), 2)                                            AS avg_value_czk
FROM transactions
GROUP BY posting_origin
ORDER BY posting_origin;


-- @query monthly_active_accounts
-- Question: how many accounts are active each month, with and without the bank's own postings?
-- Expected: active_any is almost the whole account base every month (about 4,480 of 4,500 in 1998),
--           so it says little. active_customer_initiated is the meaningful measure.
-- Technique: CTEs, COUNT(DISTINCT CASE ...), cumulative SUM() OVER for the account base.
WITH opened AS (
    SELECT d.period, COUNT(a.account_id) AS accounts_opened
    FROM dim_date AS d
    LEFT JOIN account AS a ON a.opened_date = d.date_key
    GROUP BY d.period
),
activity AS (
    SELECT
        d.period,
        COUNT(DISTINCT t.account_id) AS active_any,
        COUNT(DISTINCT CASE
            WHEN t.transaction_category NOT IN ('Interest credited', 'Penalty interest', 'Service fees')
            THEN t.account_id
        END)                          AS active_customer_initiated
    FROM dim_date AS d
    LEFT JOIN transactions AS t ON t.trans_date = d.date_key
    GROUP BY d.period
)
SELECT
    o.period,
    SUM(o.accounts_opened) OVER (ORDER BY o.period)                                                    AS open_accounts,
    a.active_any,
    a.active_customer_initiated,
    ROUND(100 * a.active_any / NULLIF(SUM(o.accounts_opened) OVER (ORDER BY o.period), 0), 1)          AS active_any_pct,
    ROUND(100 * a.active_customer_initiated / NULLIF(SUM(o.accounts_opened) OVER (ORDER BY o.period), 0), 1)
                                                                                                       AS active_customer_pct
FROM opened AS o
INNER JOIN activity AS a ON a.period = o.period
ORDER BY o.period;


-- @query activity_quartiles
-- Question: how does activity split across the least to the most active quarter of accounts?
-- Accounts are ranked by intensity (customer-initiated postings per tenure month); ties are broken by
-- account_id so the ranking is reproducible.
-- Technique: CTE chain, NTILE(4), window shares.
WITH account_activity AS (
    SELECT
        a.account_id,
        TIMESTAMPDIFF(MONTH, a.opened_date, DATE('1998-12-31')) + 1 AS tenure_months,
        COUNT(c.account_id)                                          AS postings,
        COALESCE(SUM(c.amount), 0)                                   AS value
    FROM account AS a
    LEFT JOIN transactions AS c
           ON c.account_id = a.account_id
          AND c.transaction_category NOT IN ('Interest credited', 'Penalty interest', 'Service fees')
    GROUP BY a.account_id, a.opened_date
),
ranked AS (
    SELECT
        account_id, tenure_months, postings, value,
        1.0e0 * postings / tenure_months                                              AS postings_per_month,
        NTILE(4) OVER (ORDER BY 1.0e0 * postings / tenure_months, account_id)         AS activity_quartile
    FROM account_activity
)
SELECT
    activity_quartile,
    COUNT(*)                                                           AS accounts,
    ROUND(AVG(postings_per_month), 2)                                  AS avg_postings_per_month,
    SUM(postings)                                                      AS postings,
    ROUND(100 * SUM(postings) / SUM(SUM(postings)) OVER (), 1)         AS share_of_postings_pct,
    SUM(value)                                                         AS value_czk,
    ROUND(100 * SUM(value) / SUM(SUM(value)) OVER (), 1)               AS share_of_value_pct,
    ROUND(SUM(value) / NULLIF(SUM(postings), 0), 2)                    AS avg_posting_value_czk
FROM ranked
GROUP BY activity_quartile
ORDER BY activity_quartile;


-- @query segment_summary
-- Question: how do segments differ in size, activity and value? One row per segment, long format
-- (easy to chart in Power BI). Shares are within each dimension, so they add up to 100 per dimension.
-- avg_postings_per_month is the average of the accounts' intensities (each account counts once).
-- Technique: CTE with UNION ALL over several GROUP BYs, JOINs to district, window shares by PARTITION.
WITH account_activity AS (
    SELECT
        a.account_id,
        a.owner_age_band,
        a.owner_gender,
        a.has_loan,
        a.has_card,
        a.frequency_label,
        d.region,
        TIMESTAMPDIFF(MONTH, a.opened_date, DATE('1998-12-31')) + 1 AS tenure_months,
        COUNT(c.account_id)                                          AS postings,
        COALESCE(SUM(c.amount), 0)                                   AS value
    FROM account AS a
    INNER JOIN district AS d ON d.district_id = a.district_id
    LEFT JOIN transactions AS c
           ON c.account_id = a.account_id
          AND c.transaction_category NOT IN ('Interest credited', 'Penalty interest', 'Service fees')
    GROUP BY a.account_id, a.owner_age_band, a.owner_gender, a.has_loan, a.has_card,
             a.frequency_label, d.region, a.opened_date
),
segments AS (
    SELECT 'age band' AS dimension, owner_age_band AS segment, COUNT(*) AS accounts, SUM(postings) AS postings,
           SUM(value) AS value, SUM(1.0e0 * postings / tenure_months) AS intensity_sum
    FROM account_activity GROUP BY owner_age_band
    UNION ALL
    SELECT 'gender', owner_gender, COUNT(*), SUM(postings), SUM(value), SUM(1.0e0 * postings / tenure_months)
    FROM account_activity GROUP BY owner_gender
    UNION ALL
    SELECT 'region', region, COUNT(*), SUM(postings), SUM(value), SUM(1.0e0 * postings / tenure_months)
    FROM account_activity GROUP BY region
    UNION ALL
    SELECT 'has loan', CASE WHEN has_loan = 1 THEN 'yes' ELSE 'no' END, COUNT(*), SUM(postings), SUM(value),
           SUM(1.0e0 * postings / tenure_months)
    FROM account_activity GROUP BY has_loan
    UNION ALL
    SELECT 'has card', CASE WHEN has_card = 1 THEN 'yes' ELSE 'no' END, COUNT(*), SUM(postings), SUM(value),
           SUM(1.0e0 * postings / tenure_months)
    FROM account_activity GROUP BY has_card
    UNION ALL
    SELECT 'statement frequency', frequency_label, COUNT(*), SUM(postings), SUM(value),
           SUM(1.0e0 * postings / tenure_months)
    FROM account_activity GROUP BY frequency_label
)
SELECT
    dimension,
    segment,
    accounts,
    ROUND(100 * accounts / SUM(accounts) OVER (PARTITION BY dimension), 1)    AS share_of_accounts_pct,
    ROUND(intensity_sum / accounts, 2)                                        AS avg_postings_per_month,
    ROUND(100 * postings / SUM(postings) OVER (PARTITION BY dimension), 1)    AS share_of_postings_pct,
    value                                                                     AS value_czk,
    ROUND(100 * value / SUM(value) OVER (PARTITION BY dimension), 1)          AS share_of_value_pct,
    ROUND(value / NULLIF(postings, 0), 2)                                     AS avg_posting_value_czk
FROM segments
ORDER BY dimension,
         FIELD(segment, 'under 18', '18-24', '25-34', '35-44', '45-54', '55-64', '65+'),
         segment;


-- @query concentration_deciles
-- Question: how concentrated is customer-initiated value? Decile 1 = the most valuable tenth of accounts.
-- cumulative_share_pct reads like "the top 20% of accounts make up X% of the value".
-- Technique: NTILE(10), running window total.
WITH account_value AS (
    SELECT
        a.account_id,
        COUNT(c.account_id)          AS postings,
        COALESCE(SUM(c.amount), 0)   AS value
    FROM account AS a
    LEFT JOIN transactions AS c
           ON c.account_id = a.account_id
          AND c.transaction_category NOT IN ('Interest credited', 'Penalty interest', 'Service fees')
    GROUP BY a.account_id
),
ranked AS (
    SELECT account_id, postings, value, NTILE(10) OVER (ORDER BY value DESC, account_id) AS value_decile
    FROM account_value
)
SELECT
    value_decile,
    COUNT(*)                                                                         AS accounts,
    SUM(value)                                                                       AS value_czk,
    ROUND(100 * SUM(value) / SUM(SUM(value)) OVER (), 1)                             AS share_of_value_pct,
    ROUND(100 * SUM(SUM(value)) OVER (ORDER BY value_decile) / SUM(SUM(value)) OVER (), 1)
                                                                                     AS cumulative_share_pct,
    SUM(postings)                                                                    AS postings,
    ROUND(100 * SUM(postings) / SUM(SUM(postings)) OVER (), 1)                       AS share_of_postings_pct
FROM ranked
GROUP BY value_decile
ORDER BY value_decile;


-- @query top_accounts
-- Question: who are the ten most valuable accounts, and what do they look like? (drill-through candidates)
-- Only account ids and coarse attributes are shown.
-- Technique: JOINs, ORDER BY with a tie-breaker, LIMIT.
SELECT
    a.account_id,
    a.owner_age_band,
    a.owner_gender,
    d.region,
    a.has_loan,
    COUNT(c.account_id)          AS customer_postings,
    COALESCE(SUM(c.amount), 0)   AS customer_value_czk
FROM account AS a
INNER JOIN district AS d ON d.district_id = a.district_id
LEFT JOIN transactions AS c
       ON c.account_id = a.account_id
      AND c.transaction_category NOT IN ('Interest credited', 'Penalty interest', 'Service fees')
GROUP BY a.account_id, a.owner_age_band, a.owner_gender, d.region, a.has_loan
ORDER BY customer_value_czk DESC, a.account_id
LIMIT 10;


-- @query overdraft_concentration
-- Question: are overdraft events (postings that take an account from non-negative to negative) spread over
-- many accounts, or do a few accounts repeat them? This is a reliability proxy, not a failure rate.
-- Technique: CTE with a LEFT JOIN (accounts with zero events stay), CASE bands, share over a window.
WITH per_account AS (
    SELECT
        a.account_id,
        a.has_loan,
        COALESCE(SUM(t.balance_before >= 0 AND t.balance < 0), 0) AS overdraft_events
    FROM account AS a
    LEFT JOIN transactions AS t ON t.account_id = a.account_id
    GROUP BY a.account_id, a.has_loan
)
SELECT
    CASE
        WHEN overdraft_events = 0  THEN '0'
        WHEN overdraft_events = 1  THEN '1'
        WHEN overdraft_events <= 3 THEN '2 to 3'
        WHEN overdraft_events <= 9 THEN '4 to 9'
        ELSE '10 or more'
    END                                                                              AS events_per_account,
    COUNT(*)                                                                         AS accounts,
    SUM(overdraft_events)                                                            AS overdraft_events,
    ROUND(100 * SUM(overdraft_events) / NULLIF(SUM(SUM(overdraft_events)) OVER (), 0), 1) AS share_of_events_pct,
    SUM(has_loan)                                                                    AS accounts_with_loan
FROM per_account
GROUP BY events_per_account
ORDER BY MIN(overdraft_events);


-- @query overdraft_top_accounts
-- Question: which accounts repeat overdraft events most, and what share of all events do they cause?
-- Technique: ROW_NUMBER, running share with a window, filtering on a rank.
WITH per_account AS (
    SELECT
        a.account_id,
        a.has_loan,
        SUM(t.balance_before >= 0 AND t.balance < 0) AS overdraft_events
    FROM account AS a
    INNER JOIN transactions AS t ON t.account_id = a.account_id
    GROUP BY a.account_id, a.has_loan
    HAVING SUM(t.balance_before >= 0 AND t.balance < 0) > 0
),
ranked AS (
    SELECT
        account_id, has_loan, overdraft_events,
        ROW_NUMBER() OVER (ORDER BY overdraft_events DESC, account_id)                                AS event_rank,
        ROUND(100 * SUM(overdraft_events) OVER (ORDER BY overdraft_events DESC, account_id)
              / SUM(overdraft_events) OVER (), 1)                                                    AS cumulative_share_of_events_pct
    FROM per_account
)
SELECT event_rank, account_id, has_loan, overdraft_events, cumulative_share_of_events_pct
FROM ranked
WHERE event_rank <= 10
ORDER BY event_rank;


-- @query scoreboard
-- Question: do MySQL's customer numbers agree with pandas, rebuilt from the raw files?
-- scripts/validate_sql.py recreates the owner attributes (age at opening, bands, region, products), the
-- activity tiers (including NTILE) and the concentration deciles independently.
WITH account_activity AS (
    SELECT
        a.account_id,
        a.owner_age_band,
        a.owner_gender,
        a.has_loan,
        a.has_card,
        a.frequency_label,
        d.region,
        TIMESTAMPDIFF(MONTH, a.opened_date, DATE('1998-12-31')) + 1 AS tenure_months,
        COUNT(c.account_id)                                          AS postings,
        COALESCE(SUM(c.amount), 0)                                   AS value
    FROM account AS a
    INNER JOIN district AS d ON d.district_id = a.district_id
    LEFT JOIN transactions AS c
           ON c.account_id = a.account_id
          AND c.transaction_category NOT IN ('Interest credited', 'Penalty interest', 'Service fees')
    GROUP BY a.account_id, a.owner_age_band, a.owner_gender, a.has_loan, a.has_card,
             a.frequency_label, d.region, a.opened_date
),
tiers AS (
    SELECT
        account_id, postings, value,
        NTILE(4)  OVER (ORDER BY 1.0e0 * postings / tenure_months, account_id) AS activity_quartile,
        NTILE(10) OVER (ORDER BY value DESC, account_id)                       AS value_decile
    FROM account_activity
),
segments AS (
    SELECT 'age band' AS dimension, owner_age_band AS segment, COUNT(*) AS accounts, SUM(postings) AS postings,
           SUM(value) AS value, SUM(1.0e0 * postings / tenure_months) AS intensity_sum
    FROM account_activity GROUP BY owner_age_band
    UNION ALL
    SELECT 'gender', owner_gender, COUNT(*), SUM(postings), SUM(value), SUM(1.0e0 * postings / tenure_months)
    FROM account_activity GROUP BY owner_gender
    UNION ALL
    SELECT 'region', region, COUNT(*), SUM(postings), SUM(value), SUM(1.0e0 * postings / tenure_months)
    FROM account_activity GROUP BY region
    UNION ALL
    SELECT 'has loan', CASE WHEN has_loan = 1 THEN 'yes' ELSE 'no' END, COUNT(*), SUM(postings), SUM(value),
           SUM(1.0e0 * postings / tenure_months)
    FROM account_activity GROUP BY has_loan
    UNION ALL
    SELECT 'has card', CASE WHEN has_card = 1 THEN 'yes' ELSE 'no' END, COUNT(*), SUM(postings), SUM(value),
           SUM(1.0e0 * postings / tenure_months)
    FROM account_activity GROUP BY has_card
    UNION ALL
    SELECT 'statement frequency', frequency_label, COUNT(*), SUM(postings), SUM(value),
           SUM(1.0e0 * postings / tenure_months)
    FROM account_activity GROUP BY frequency_label
),
monthly AS (
    SELECT
        d.period,
        COUNT(DISTINCT t.account_id) AS active_any,
        COUNT(DISTINCT CASE
            WHEN t.transaction_category NOT IN ('Interest credited', 'Penalty interest', 'Service fees')
            THEN t.account_id
        END)                          AS active_customer_initiated
    FROM dim_date AS d
    LEFT JOIN transactions AS t ON t.trans_date = d.date_key
    GROUP BY d.period
),
overdraft AS (
    SELECT
        a.account_id,
        COALESCE(SUM(t.balance_before >= 0 AND t.balance < 0), 0) AS events
    FROM account AS a
    LEFT JOIN transactions AS t ON t.account_id = a.account_id
    GROUP BY a.account_id
),
overdraft_banded AS (
    SELECT
        CASE
            WHEN events = 0  THEN '0'
            WHEN events = 1  THEN '1'
            WHEN events <= 3 THEN '2 to 3'
            WHEN events <= 9 THEN '4 to 9'
            ELSE '10 or more'
        END AS band,
        events
    FROM overdraft
),
origin AS (
    SELECT
        CASE WHEN transaction_category IN ('Interest credited', 'Penalty interest', 'Service fees')
             THEN 'Bank-generated' ELSE 'Customer-initiated' END AS posting_origin,
        amount
    FROM transactions
),
top_accounts AS (
    SELECT value, ROW_NUMBER() OVER (ORDER BY value DESC, account_id) AS value_rank
    FROM account_activity
)
SELECT CONCAT('origin_postings|', posting_origin) AS metric, COUNT(*) AS value FROM origin GROUP BY posting_origin
UNION ALL SELECT CONCAT('origin_value|', posting_origin), SUM(amount) FROM origin GROUP BY posting_origin
UNION ALL SELECT CONCAT('monthly_active_any|', period),               active_any                FROM monthly
UNION ALL SELECT CONCAT('monthly_active_customer|', period),          active_customer_initiated FROM monthly
UNION ALL SELECT CONCAT('quartile_accounts|', activity_quartile), COUNT(*)      FROM tiers GROUP BY activity_quartile
UNION ALL SELECT CONCAT('quartile_postings|', activity_quartile), SUM(postings) FROM tiers GROUP BY activity_quartile
UNION ALL SELECT CONCAT('quartile_value|', activity_quartile),    SUM(value)    FROM tiers GROUP BY activity_quartile
UNION ALL SELECT CONCAT('decile_accounts|', value_decile),        COUNT(*)      FROM tiers GROUP BY value_decile
UNION ALL SELECT CONCAT('decile_postings|', value_decile),        SUM(postings) FROM tiers GROUP BY value_decile
UNION ALL SELECT CONCAT('decile_value|', value_decile),           SUM(value)    FROM tiers GROUP BY value_decile
UNION ALL SELECT CONCAT('segment_accounts|', dimension, '|', segment),  accounts FROM segments
UNION ALL SELECT CONCAT('segment_postings|', dimension, '|', segment),  postings FROM segments
UNION ALL SELECT CONCAT('segment_value|', dimension, '|', segment),     value    FROM segments
UNION ALL SELECT CONCAT('avg_postings_per_month|', dimension, '|', segment), ROUND(intensity_sum / accounts, 2) FROM segments
UNION ALL SELECT CONCAT('overdraft_band_accounts|', band), COUNT(*)    FROM overdraft_banded GROUP BY band
UNION ALL SELECT CONCAT('overdraft_band_events|', band),   SUM(events) FROM overdraft_banded GROUP BY band
UNION ALL SELECT CONCAT('top_account_value|', value_rank), value FROM top_accounts WHERE value_rank <= 10;
